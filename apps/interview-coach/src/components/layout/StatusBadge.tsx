"use client";

import { Info } from "lucide-react";
import { useAiStatus } from "./StatusProvider";

/** "Live AI (Claude)" vs "Demo mode" pill with an explanatory popover. */
export function StatusBadge() {
  const status = useAiStatus();

  if (status.state === "loading") {
    return (
      <span className="inline-flex h-8 w-28 animate-pulse items-center rounded-full bg-white/5 ring-1 ring-inset ring-white/10" aria-label="Checking AI status" role="status" />
    );
  }

  const live = status.state === "ready" && status.mode === "live";
  const label = status.state === "error" ? "Status unavailable" : live ? "Live AI (Claude)" : "Demo mode";

  return (
    <>
      <button
        type="button"
        popoverTarget="ai-status-popover"
        className={`inline-flex h-8 items-center gap-2 rounded-full px-3 text-xs font-medium ring-1 ring-inset transition ${
          live
            ? "bg-emerald-400/10 text-emerald-200 ring-emerald-400/30 hover:bg-emerald-400/15"
            : status.state === "error"
              ? "bg-white/5 text-zinc-300 ring-white/15 hover:bg-white/10"
              : "bg-amber-400/10 text-amber-200 ring-amber-400/30 hover:bg-amber-400/15"
        }`}
      >
        <span className="relative flex size-2" aria-hidden>
          {live && <span className="absolute inline-flex size-full animate-ping rounded-full bg-emerald-400 opacity-60" />}
          <span className={`relative inline-flex size-2 rounded-full ${live ? "bg-emerald-400" : status.state === "error" ? "bg-zinc-400" : "bg-amber-400"}`} />
        </span>
        {label}
        <Info className="size-3.5 opacity-70" aria-hidden />
      </button>

      <div
        id="ai-status-popover"
        popover="auto"
        className="fixed inset-auto top-16 right-[max(1rem,calc((100vw-72rem)/2+1.5rem))] m-0 w-[min(22rem,calc(100vw-2rem))] rounded-2xl border border-white/10 bg-ink-800 p-5 text-sm text-zinc-300 shadow-2xl shadow-black/50"
      >
        {live ? (
          <>
            <p className="font-semibold text-white">Live AI is on</p>
            <p className="mt-2 leading-relaxed">
              Questions, feedback and reports are generated by Claude
              {status.state === "ready" && status.model ? (
                <>
                  {" "}
                  (<code className="text-xs text-zinc-200">{status.model}</code>)
                </>
              ) : null}
              . Follow-up questions adapt to your previous answers.
            </p>
          </>
        ) : status.state === "error" ? (
          <>
            <p className="font-semibold text-white">Couldn&apos;t check the AI status</p>
            <p className="mt-2 leading-relaxed">The status endpoint didn&apos;t respond. Interviews will still try to run — refresh the page to check again.</p>
          </>
        ) : (
          <>
            <p className="font-semibold text-white">You&apos;re in demo mode</p>
            <p className="mt-2 leading-relaxed">
              No API key is configured, so questions come from a curated bank of 80+ interview questions and answers are scored by a
              transparent heuristic (detail, structure, STAR and key concepts). The full flow works exactly the same.
            </p>
            <p className="mt-2 leading-relaxed text-zinc-400">
              Site owners: set <code className="text-xs text-zinc-200">ANTHROPIC_API_KEY</code> to enable Claude.
            </p>
          </>
        )}
      </div>
    </>
  );
}
