import { levelLabel, READINESS_LABEL, roleTitle, typeLabel, VERDICT_LABEL } from "./constants";
import { formatDuration, splitInterviewerTurn } from "./interview";
import type { Report, Session } from "./schemas";

export function formatDate(timestamp: number): string {
  return new Intl.DateTimeFormat("en-IN", { dateStyle: "medium", timeStyle: "short" }).format(timestamp);
}

const quote = (text: string) =>
  text
    .trim()
    .split("\n")
    .map((line) => `> ${line}`)
    .join("\n");

/** Serialises a finished interview and its report as a portable Markdown document. */
export function reportToMarkdown(session: Session, report: Report): string {
  const { config } = session;
  const lines: string[] = [
    `# Interview report — ${roleTitle(config.role)} (${levelLabel(config.level)})`,
    "",
    `- **Date:** ${formatDate(session.createdAt)}`,
    ...(config.name ? [`- **Candidate:** ${config.name}`] : []),
    `- **Interview:** ${typeLabel(config.type)} · ${config.questionCount} questions${config.jobDescription ? " · tailored to a job description" : ""}`,
    `- **Overall score:** ${report.overallScore}/100 — ${READINESS_LABEL[report.readiness]}`,
    `- **Generated by:** ${session.reportMode === "live" ? "Claude (live AI)" : "Demo mode (transparent heuristic scoring)"}`,
    "",
    "## Summary",
    "",
    report.summary,
    "",
  ];

  const section = (title: string, items: string[], ordered = false) => {
    if (!items.length) return;
    lines.push(`## ${title}`, "", ...items.map((item, i) => `${ordered ? `${i + 1}.` : "-"} ${item}`), "");
  };
  section("Top strengths", report.topStrengths);
  section("Focus areas", report.focusAreas);
  section("Next steps", report.nextSteps, true);

  lines.push("## Competencies", "", "| Competency | Score |", "| --- | --- |");
  for (const competency of report.competencies) {
    lines.push(`| ${competency.name} | ${competency.score.toFixed(1)} / 10 |`);
  }
  lines.push("", "## Question by question", "");

  session.turns.forEach((turn, index) => {
    const evaluation = turn.evaluation;
    const heading = turn.skipped
      ? "Skipped"
      : evaluation
        ? `${evaluation.score}/10 · ${VERDICT_LABEL[evaluation.verdict]}`
        : "Not scored";
    const { question } = splitInterviewerTurn(turn.question);
    lines.push(`### Q${index + 1} (${turn.kind}) — ${heading}`, "", `**Question:** ${question.replace(/\n+/g, " ")}`, "");
    if (turn.skipped) {
      lines.push("_You skipped this question._", "");
      return;
    }
    lines.push(`**Your answer** (${formatDuration(turn.durationSec)}):`, "", quote(turn.answer), "");
    if (evaluation) {
      lines.push(
        "**What worked:**",
        ...evaluation.strengths.map((item) => `- ${item}`),
        "",
        "**How to improve:**",
        ...evaluation.improvements.map((item) => `- ${item}`),
        "",
        "**Model answer:**",
        "",
        quote(evaluation.idealAnswer),
        "",
      );
    }
  });

  lines.push("---", "", "_Generated with AI Interview Coach — https://ai-interview-coach-jeevan.vercel.app_", "");
  return lines.join("\n");
}

export function downloadTextFile(filename: string, content: string, type = "text/markdown;charset=utf-8") {
  const url = URL.createObjectURL(new Blob([content], { type }));
  const link = document.createElement("a");
  link.href = url;
  link.download = filename;
  document.body.append(link);
  link.click();
  link.remove();
  // Revoking synchronously can cancel the download in some browsers.
  window.setTimeout(() => URL.revokeObjectURL(url), 1000);
}

export function reportFilename(session: Session): string {
  const date = new Date(session.createdAt).toISOString().slice(0, 10);
  return `interview-report-${session.config.role}-${date}.md`;
}
